"""
СРАВНЕНИЕ СЛОВАРЕЙ В PYTHON
==============================
Словари сравниваются по содержимому, а НЕ по порядку элементов.
Порядок ключей не важен при сравнении.
"""

# ============================================
# 1. СРАВНЕНИЕ СЛОВАРЕЙ
# ============================================

person = {
    "name": "John",
    "age": 30,
    "city": "New York"
}

other_person = {
    "city": "New York",
    "age": 30,
    "name": "John",
}

# Порядок ключей НЕ важен!
print(person == other_person)  # True

# Сравнение с оператором !=:
print(person != other_person)  # False


# ============================================
# 2. ЧТО ВАЖНО ПРИ СРАВНЕНИИ
# ============================================

# Сравниваются и ключи, и значения:
person_1 = {"name": "John", "age": 30}
person_2 = {"name": "John", "age": 31}  # другое значение
print(person_1 == person_2)  # False

person_3 = {"name": "John", "age": 30}
person_4 = {"name": "John"}  # нет ключа 'age'
print(person_3 == person_4)  # False

# Разные типы значений:
print({"age": 30} == {"age": "30"})  # False (int ≠ str)


# ============================================
# 3. СРАВНЕНИЕ С ДРУГИМИ ТИПАМИ
# ============================================

# Словарь НЕ равен списку кортежей:
person = {"name": "John", "age": 30}
pairs = [("name", "John"), ("age", 30)]
print(person == pairs)  # False

# Но можно преобразовать:
print(person == dict(pairs))  # True


# ============================================
# 4. ВЛОЖЕННЫЕ СЛОВАРИ
# ============================================

# Сравнение вложенных словарей:
user_1 = {
    "name": "Alice",
    "address": {"city": "Moscow", "zip": "101000"}
}

user_2 = {
    "name": "Alice",
    "address": {"zip": "101000", "city": "Moscow"}  # порядок другой
}

print(user_1 == user_2)  # True (вложенные тоже сравниваются по содержимому)


# ============================================
# 5. ПРАКТИЧЕСКИЕ ПРИМЕРЫ
# ============================================

# 1. Проверка изменений в конфигурации:
config_before = {"debug": True, "port": 8080}
config_after = {"port": 8080, "debug": True}

if config_before == config_after:
    print("Конфигурация не изменилась")

# 2. Поиск различий:
config_1 = {"debug": True, "port": 8080, "host": "localhost"}
config_2 = {"debug": False, "port": 8080, "host": "localhost"}

# Различия по ключам:
only_in_1 = config_1.keys() - config_2.keys()
only_in_2 = config_2.keys() - config_1.keys()
print(f"Только в первом: {only_in_1}")   # set()
print(f"Только во втором: {only_in_2}")  # set()

# Различия по значениям:
for key in config_1.keys() & config_2.keys():
    if config_1[key] != config_2[key]:
        print(f"{key}: {config_1[key]} → {config_2[key]}")
# debug: True → False

# 3. Сравнение с пустым словарём:
person = {}
if not person:
    print("Словарь пуст")

print(person == {})  # True


# ============================================
# 6. КЛЮЧЕВЫЕ МОМЕНТЫ
# ============================================

"""
✅ ЧТО ВАЖНО ЗНАТЬ:

1. Порядок ключей НЕ важен при сравнении
   {"a": 1, "b": 2} == {"b": 2, "a": 1}  # True

2. Сравниваются И ключи, И значения
   {"a": 1} == {"a": 2}  # False

3. Вложенные словари сравниваются рекурсивно
   {"x": {"a": 1}} == {"x": {"a": 1}}  # True

4. Типы значений важны
   {"age": 30} == {"age": "30"}  # False

5. Словарь ≠ список кортежей
   {"a": 1} == [("a", 1)]  # False

6. Пустые словари равны
   {} == dict()  # True
"""