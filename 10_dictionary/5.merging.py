"""
ОБЪЕДИНЕНИЕ СЛОВАРЕЙ В PYTHON
================================
Существует несколько способов объединить два словаря.
Важно: при конфликте ключей побеждает значение из ПРАВОГО словаря.
"""

# ============================================
# ИСХОДНЫЕ ДАННЫЕ
# ============================================

person = {
    "city": "New York",
    "age": 30,
    "name": "John",
}

add_person_info = {
    "job": "Engineer",
    "married": True,
    "city": "London"  # конфликтующий ключ!
}


# ============================================
# 1. МЕТОД UPDATE() — ИЗМЕНЯЕТ СЛОВАРЬ
# ============================================

person = {
    "city": "New York",
    "age": 30,
    "name": "John",
}

person.update(add_person_info)
print(person)
# {'city': 'London', 'age': 30, 'name': 'John', 'job': 'Engineer', 'married': True}

# ?? update() изменяет ИСХОДНЫЙ словарь и возвращает None!
# result = person.update(...)  # result = None

# Обновление с перезаписью:
person_1 = {"a": 1, "b": 2}
person_1.update({"b": 99, "c": 3})
print(person_1)  # {'a': 1, 'b': 99, 'c': 3}


# ============================================
# 2. РАСПАКОВКА {**d1, **d2} — СОЗДАЁТ НОВЫЙ
# ============================================

person = {
    "city": "New York",
    "age": 30,
    "name": "John",
}

dct_join = {**person, **add_person_info}
print(dct_join)
# {'city': 'London', 'age': 30, 'name': 'John', 'job': 'Engineer', 'married': True}

# ? Создаёт НОВЫЙ словарь, оригиналы не изменяются
print(person)  # оригинал без изменений!

# Работает с любым количеством словарей:
d1 = {"a": 1}
d2 = {"b": 2}
d3 = {"c": 3}
merged = {**d1, **d2, **d3}
print(merged)  # {'a': 1, 'b': 2, 'c': 3}

# Порядок важен:
d1 = {"a": 1, "b": 1}
d2 = {"b": 2, "c": 2}
print({**d1, **d2})  # {'a': 1, 'b': 2, 'c': 2}
print({**d2, **d1})  # {'b': 1, 'c': 2, 'a': 1}


# ============================================
# 3. ОПЕРАТОР | (Python 3.9+) — СОЗДАЁТ НОВЫЙ
# ============================================

person = {
    "city": "New York",
    "age": 30,
    "name": "John",
}

person = person | add_person_info
print(person)
# {'city': 'London', 'age': 30, 'name': 'John', 'job': 'Engineer', 'married': True}

# ? Создаёт НОВЫЙ словарь (присваивание обязательно)

# Можно без присваивания:
merged = person | add_person_info
print(merged)

# Объединение нескольких словарей:
d1 = {"a": 1}
d2 = {"b": 2}
d3 = {"c": 3}
merged = d1 | d2 | d3
print(merged)  # {'a': 1, 'b': 2, 'c': 3}


# ============================================
# 4. ОПЕРАТОР |= (Python 3.9+) — ИЗМЕНЯЕТ СЛОВАРЬ
# ============================================

person = {
    "city": "New York",
    "age": 30,
    "name": "John",
}

person |= add_person_info
print(person)
# {'city': 'London', 'age': 30, 'name': 'John', 'job': 'Engineer', 'married': True}

# ?? |= изменяет исходный словарь (аналог update())


