"""
? update() — когда:
- Нужно изменить существующий словарь
- Не важна "чистота" оригинала
- Python < 3.9

? {**d1, **d2} — когда:
- Нужен новый словарь без изменения оригиналов
- Работаете с Python 3.5+
- Самый универсальный способ

? d1 | d2 — когда:
- Нужен новый словарь без изменения оригиналов
- Python 3.9+ (современный синтаксис)
- Более читаемый, чем распаковка

? d1 |= d2 — когда:
- Нужно изменить существующий словарь
- Python 3.9+
- Более читаемый, чем update()
"""


