# ============================================
# 6. КОНФЛИКТ КЛЮЧЕЙ
# ============================================

# Побеждает значение из ПРАВОГО словаря:
left = {"a": 1, "b": 2}
right = {"b": 99, "c": 3}

print({**left, **right})   # {'a': 1, 'b': 99, 'c': 3}
print({**right, **left})   # {'b': 2, 'c': 3, 'a': 1}

# Аналогично для |:
print(left | right)  # {'a': 1, 'b': 99, 'c': 3}
print(right | left)  # {'b': 2, 'c': 3, 'a': 1}


# ============================================
# 7. ВЛОЖЕННЫЕ СЛОВАРИ — ВАЖНО!
# ============================================

# ?? ВНИМАНИЕ: объединение поверхностное!
d1 = {"user": {"name": "Alice", "age": 25}}
d2 = {"user": {"city": "Moscow"}}

merged = {**d1, **d2}
print(merged)  # {'user': {'city': 'Moscow'}} — первый словарь ПОТЕРЯН!

# ? Для глубокого объединения нужна отдельная логика:
def deep_merge(d1, d2):
    """Рекурсивное объединение словарей"""
    result = d1.copy()
    for key, value in d2.items():
        if key in result and isinstance(result[key], dict) and isinstance(value, dict):
            result[key] = deep_merge(result[key], value)
        else:
            result[key] = value
    return result

d1 = {"user": {"name": "Alice", "age": 25}}
d2 = {"user": {"city": "Moscow"}}
merged = deep_merge(d1, d2)
print(merged)  # {'user': {'name': 'Alice', 'age': 25, 'city': 'Moscow'}}


# ============================================
# 8. ПРАКТИЧЕСКИЕ ПРИМЕРЫ
# ============================================

# 1. Настройки по умолчанию:
defaults = {"theme": "light", "font_size": 12, "language": "ru"}
user_settings = {"theme": "dark"}

# Способ 1: update (изменяет defaults!)
config = defaults.copy()
config.update(user_settings)
print(config)  # {'theme': 'dark', 'font_size': 12, 'language': 'ru'}

# Способ 2: распаковка (рекомендуется)
config = {**defaults, **user_settings}
print(config)  # {'theme': 'dark', 'font_size': 12, 'language': 'ru'}

# Способ 3: оператор |
config = defaults | user_settings
print(config)  # {'theme': 'dark', 'font_size': 12, 'language': 'ru'}

# 2. Объединение данных пользователя:
user = {"name": "John", "age": 30}
extra = {"email": "john@mail.com", "phone": "+1234567890"}
full_user = {**user, **extra}
print(full_user)

# 3. Слияние нескольких источников:
api_data = {"status": "ok", "user_id": 42}
cache_data = {"user_id": 42, "cached": True}
db_data = {"name": "Alice", "email": "alice@mail.com"}

merged = {**api_data, **cache_data, **db_data}
print(merged)
# {'status': 'ok', 'user_id': 42, 'cached': True, 'name': 'Alice', 'email': 'alice@mail.com'}


