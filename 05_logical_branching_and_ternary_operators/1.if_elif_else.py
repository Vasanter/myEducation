# ============================================
# 11. УСЛОВНЫЕ ВЫРАЖЕНИЯ В КОЛЛЕКЦИЯХ
# ============================================

# Условный оператор в списковом включении:
numbers = [-5, -2, 0, 3, 8, -1]
positive = [num for num in numbers if num > 0]
negative = [num for num in numbers if num < 0]
zeros = [num for num in numbers if num == 0]

print(f"Положительные: {positive}")
print(f"Отрицательные: {negative}")
print(f"Нули: {zeros}")

# Классификация чисел:
classified = ["positive" if num > 0 else "negative" if num < 0 else "zero" for num in numbers]
print(f"Классификация: {classified}")


