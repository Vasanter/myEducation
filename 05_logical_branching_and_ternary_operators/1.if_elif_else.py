# 8. ПРОВЕРКА ВИСОКОСНОГО ГОДА
# ============================================

year = int(input("Введите год: "))

# Условия високосного года:
if year % 4 == 0 and year % 100 != 0 or year % 400 == 0:
    print("Год високосный")
else:
    print("Год невисокосный")

# Более читаемая версия:
is_leap = (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0)
if is_leap:
    print("Год високосный")
else:
    print("Год невисокосный")


# ============================================
# 9. ПРОВЕРКА ЗАПОЛНЕНИЯ ПОЛЯ
# ============================================

username = input("Введите логин: ")

# Требования: 3-10 символов, только буквы, первая заглавная, остальные строчные
if 3 <= len(username) <= 10 and \
        username.isalpha() and \
        username[0].isupper() and \
        username[1:].islower():
    print("Логин соответствует требованиям!")
else:
    # Детальная проверка ошибок:
    if len(username) < 3:
        print("Логин слишком короткий (минимум 3 символа)")
    elif len(username) > 10:
        print("Логин слишком длинный (максимум 10 символов)")

    if not username.isalpha():
        print("В строке присутствуют не только буквы!")

    if username and not username[0].isupper():
        print("Первая буква должна быть заглавной!")

    if len(username) > 1 and not username[1:].islower():
        print("Буквы после заглавной должны быть строчными!")


# ============================================
# 10. ТЕРНАРНЫЙ ОПЕРАТОР (ОДНОСТРОЧНЫЙ IF)
