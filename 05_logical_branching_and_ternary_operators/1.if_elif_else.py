"""
УСЛОВНЫЙ ОПЕРАТОР IF-ELIF-ELSE В PYTHON
==========================================
Условный оператор позволяет выполнять код в зависимости от условий.
"""

# ============================================
# 1. БАЗОВЫЙ СИНТАКСИС IF
# ============================================

# Простое условие:
if True:
    print("Hello, world!")  # Hello, world!

if False:
    print("Это не выполнится")

# Проверка истинности значений:
message = "Hello, world!"
if message:  # True, так как строка не пустая
    print("Сообщение не пустое!")

# Значения, которые считаются False:
if not 0:  # 0 — False
    print("0 считается False")

if not "":  # пустая строка — False
    print("Пустая строка считается False")

if not []:  # пустой список — False
    print("Пустой список считается False")


# ============================================
# 2. IF-ELSE
# ============================================

something = input("Введи что-нибудь: ")

if something:
    print(f'Ты ввёл => {something}')
else:
    print('Вы ничего не ввели!')


# ============================================
# 3. IF-ELIF-ELSE
# ============================================

num = int(input("Введите любое число: "))

if num > 0:
    print(f"Число {num} положительное")
elif num < 0:
    print(f"Число {num} отрицательное")
else:
    print("Введённое число равно нулю")


# ============================================
# 4. ПРОВЕРКА ДИАПАЗОНА
# ============================================

num = int(input("Введите число: "))

# Цепочка сравнений (рекомендуется):
if 10 <= num <= 20:
    print('Число находится в диапазоне между 10 и 20!')
else:
    print('Число вне диапазона 10-20')

# Альтернативная запись с and:
if num >= 10 and num <= 20:
    print('Число находится в диапазоне')


# ============================================
# 5. ВЛОЖЕННЫЕ УСЛОВИЯ (НЕ РЕКОМЕНДУЕТСЯ)
# ============================================

num1 = 10
num2 = 20

# Плохой стиль (вложенные if):
if num1 > 0:
    if num2 > 0:
        print("num1 и num2 положительные")

# Хороший стиль (объединение условий):
if num1 > 0 and num2 > 0:
    print("num1 и num2 положительные")


