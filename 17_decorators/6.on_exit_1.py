"""
МОДУЛЬ ATEXIT — ОБРАБОТЧИКИ ЗАВЕРШЕНИЯ ПРОГРАММЫ
====================================================
atexit позволяет регистрировать функции, которые будут вызваны
автоматически при нормальном завершении программы.

Когда вызываются:
- При завершении скрипта (достигнут конец)
- При вызове sys.exit()
- При вызове exit() / quit()
- При получении SIGTERM (на Unix)

Когда НЕ вызываются:
- При os._exit() (принудительное завершение)
- При SIGKILL (kill -9)
- При необработанном исключении — ВЫЗЫВАЮТСЯ (но программа падает)
"""

import atexit


# ============================================
# 1. РЕГИСТРАЦИЯ ОБРАБОТЧИКА
# ============================================

@atexit.register
def exit_handler() -> None:
    """Вызывается при завершении программы"""
    print("We're exiting now!")


def main() -> None:
    for i in range(10):
        print(2 ** i)


if __name__ == "__main__":
    main()

    # ?? Отменяем регистрацию — обработчик НЕ вызовется
    atexit.unregister(exit_handler)

    # ?? Исключение — программа упадёт, но обработчик уже отменён
    1 / 0