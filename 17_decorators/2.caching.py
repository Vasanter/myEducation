"""
ДЕКОРАТОР @CACHE ИЗ FUNCTOOLS
================================
@cache — это встроенный декоратор (Python 3.9+), который автоматически
кэширует результаты функции. При повторном вызове с теми же аргументами
функция НЕ выполняется — возвращается сохранённый результат.

Преимущества:
- Ускоряет выполнение «дорогих» операций
- Не требует ручной реализации кэша
- Потокобезопасен

?? Применяйте только к ЧИСТЫМ функциям:
   - одинаковые аргументы ? одинаковый результат
   - без побочных эффектов
"""

import time
from functools import cache


# ============================================
# 1. ОСНОВНАЯ ФУНКЦИЯ С КЭШИРОВАНИЕМ
# ============================================

@cache
def count_vowels(text: str) -> int:
    """
    Подсчитывает количество гласных в строке.

    Благодаря @cache, повторные вызовы с той же строкой
    не выполняют функцию заново, а берут результат из кэша.

    Args:
        text: Строка для анализа.

    Returns:
        Количество гласных (int).
    """
    vowel_count: int = 0

    # Имитация «дорогой» операции:
    print(f'Bot: Counting vowels in: "{text}"...')
    time.sleep(2)

    # Подсчёт гласных:
    for letter in text:
        if letter in 'aeiouAEIOU':
            vowel_count += 1

    return vowel_count


# ============================================
# 2. ОСНОВНОЙ ЦИКЛ ПРОГРАММЫ
# ============================================

def main() -> None:
    """
    Основной цикл программы.

    Команды:
        !info  — показать статистику кэша
        !clear — очистить кэш
        любое  — подсчитать гласные в строке
    """
    while True:
        user_input: str = input('You: ')

        # Команда: показать статистику кэша
        if user_input == '!info':
            print(f'Bot: {count_vowels.cache_info()}')

        # Команда: очистить кэш
        elif user_input == '!clear':
            print('Bot: Cache cleared!')
            count_vowels.cache_clear()

        # Обычный ввод: подсчёт гласных
        else:
            print(
                f'Bot: "{user_input}" contains '
                f'{count_vowels(user_input)} vowels.'
            )


if __name__ == '__main__':
    main()