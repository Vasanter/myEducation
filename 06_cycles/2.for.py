# 16. СОРТИРОВКА ПУЗЫРЬКОМ
# ============================================

"""
Алгоритм:
1. Проходим по элементам массива.
2. Попарно сравниваем соседние элементы.
3. Если левый больше правого — меняем местами.
4. Повторяем, пока массив не отсортирован.
"""

N = 10  # количество элементов
a = [randint(1, 99) for _ in range(N)]
print("Исходный список:", a)

# Сортировка:
for i in range(N - 1):
    for j in range(N - 1 - i):
        if a[j] > a[j + 1]:
            a[j], a[j + 1] = a[j + 1], a[j]  # обмен через кортеж

print("Отсортированный:", a)

# Альтернатива — встроенная сортировка:
a.sort()
print("sorted():", a)


