# 10. КОГДА ИСПОЛЬЗОВАТЬ WHILE, А КОГДА FOR
# ============================================

"""
✅ WHILE — когда:
- Количество итераций заранее неизвестно
- Цикл зависит от условия (не от счётчика)
- Нужен бесконечный цикл с break
- Ввод данных до наступления условия

✅ FOR — когда:
- Известно количество итераций
- Нужно перебрать элементы коллекции
- Есть диапазон range()

Пример:
- while: "Вводите пароль, пока он не совпадёт"
- for: "Вывести числа от 1 до 10"
"""

# Сравнение:
# WHILE:
n = 1
while n <= 10:
    print(n, end=' ')
    n += 1
print()

# FOR (то же самое, но короче):
for n in range(1, 11):
    print(n, end=' ')
print()


