# Ручное заполнение списка:
length = int(input("Enter length: "))
user_list = []
i = 1

while i < length + 1:
    user_list.append(int(input(f"Enter element # {i}: ")))
    i += 1

print(user_list)

# Через списковое включение (List Comprehension) — лаконичнее:
length = int(input("Enter length: "))
user_list = [int(input(f"Enter element # {i}: ")) for i in range(1, length + 1)]
print(user_list)


