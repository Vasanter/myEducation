"""
ОПЕРАТОРЫ ПРИСВАИВАНИЯ В PYTHON
================================
Операторы присваивания используются для присвоения значений переменным.
"""

# ============================================
# 1. ОБЫЧНОЕ ПРИСВАИВАНИЕ (=)
# ============================================

x = 5
print(x)  # 5

# Присваивание разных типов:
name = "Alice"  # строка
pi = 3.14  # float
is_active = True  # bool
numbers = [1, 2, 3]  # список

# ============================================
# 2. МНОЖЕСТВЕННОЕ ПРИСВАИВАНИЕ
# ============================================

# Все переменные получают одно значение:
x = y = z = 0
print(x, y, z)  # 0 0 0

# Практическое применение:
counter = total = max_value = 0
a = b = c = None  # инициализация пустыми значениями

# ============================================
# 3. ПОСЛЕДОВАТЕЛЬНОЕ ПРИСВАИВАНИЕ
# ============================================

# Разные значения разным переменным:
a, b, c = 1, 2, 3
print(a, b, c)  # 1 2 3

# Обмен значениями (без временной переменной):
x = 10
y = 20
print(f"До обмена: x={x}, y={y}")
x, y = y, x
print(f"После обмена: x={x}, y={y}")

# Распаковка последовательностей:
first, second, third = [1, 2, 3]
print(first, second, third)  # 1 2 3

# Распаковка кортежа:
name, age, city = ("Alice", 30, "New York")
print(name, age, city)  # Alice 30 New York

# Распаковка со звёздочкой:
first, *rest = [1, 2, 3, 4, 5]
print(f"Первый: {first}, Остальные: {rest}")  # Первый: 1, Остальные: [2, 3, 4, 5]

*first, last = [1, 2, 3, 4, 5]
print(f"Первые: {first}, Последний: {last}")  # Первые: [1, 2, 3, 4], Последний: 5

first, *middle, last = [1, 2, 3, 4, 5]
print(f"Первый: {first}, Средние: {middle}, Последний: {last}")  # Первый: 1, Средние: [2, 3, 4], Последний: 5

# ============================================
# 4. АРИФМЕТИЧЕСКИЕ ОПЕРАТОРЫ ПРИСВАИВАНИЯ
# ============================================

# += (плюс равно)
x = 5
x += 3  # эквивалентно x = x + 3
print(f"x += 3: {x}")  # 8

# Работа со строками:
text = "Hello"
text += " World"
print(text)  # Hello World

# Работа со списками:
numbers = [1, 2]
numbers += [3, 4]
print(numbers)  # [1, 2, 3, 4]

# -= (минус равно)
x = 5
x -= 3  # эквивалентно x = x - 3
print(f"x -= 3: {x}")  # 2

# *= (умножить равно)
x = 5
x *= 3  # эквивалентно x = x * 3
print(f"x *= 3: {x}")  # 15

# Работа со строками:
text = "Ha"
text *= 3
print(text)  # HaHaHa

# Работа со списками:
numbers = [1, 2]
numbers *= 3
print(numbers)  # [1, 2, 1, 2, 1, 2]

# /= (делить равно)
x = 10
x /= 2  # эквивалентно x = x / 2
print(f"x /= 2: {x}")  # 5.0

# //= (целочисленное деление равно)
x = 10
x //= 3  # эквивалентно x = x // 3
print(f"x //= 3: {x}")  # 3

# **= (возведение в степень равно)
x = 2
x **= 3  # эквивалентно x = x ** 3
print(f"x **= 3: {x}")  # 8

# %= (остаток от деления равно)
x = 17
x %= 5  # эквивалентно x = x % 5
print(f"x %= 5: {x}")  # 2

# ============================================
# 5. ПОБИТОВЫЕ ОПЕРАТОРЫ ПРИСВАИВАНИЯ
# ============================================

# &= (побитовое И)
x = 12  # 1100 в двоичной
x &= 10  # 1010 в двоичной
print(f"x &= 10: {x}")  # 8 (1000 в двоичной)

# |= (побитовое ИЛИ)
x = 12  # 1100
x |= 10  # 1010
print(f"x |= 10: {x}")  # 14 (1110)

# ^= (побитовое исключающее ИЛИ)
x = 12  # 1100
x ^= 10  # 1010
print(f"x ^= 10: {x}")  # 6 (0110)

# >>= (сдвиг вправо)
x = 8  # 1000
x >>= 2  # сдвиг на 2 позиции вправо
print(f"x >>= 2: {x}")  # 2 (0010)

# <<= (сдвиг влево)
x = 2  # 0010
x <<= 2  # сдвиг на 2 позиции влево
print(f"x <<= 2: {x}")  # 8 (1000)

# ============================================
# 6. ОПЕРАТОР := (МОРЖОВЫЙ ОПЕРАТОР)
# ============================================
# Python 3.8+ позволяет присваивать значения в выражениях

# Без моржового оператора:
n = len("Hello")
if n > 3:
    print(f"Длина строки {n} больше 3")

# С моржовым оператором:
if (n := len("Hello")) > 3:
    print(f"Длина строки {n} больше 3")

# Использование в циклах:
while (line := input("Введите текст (или 'quit'): ")) != 'quit':
    print(f"Вы ввели: {line}")

# Использование в списковых включениях:
numbers = [1, 2, 3, 4, 5]
squared = [y for x in numbers if (y := x ** 2) > 10]
print(squared)  # [16, 25]

# ============================================
# 7. ЦЕПОЧКИ ПРИСВАИВАНИЯ
# ============================================

# Цепочка сравнений с присваиванием:
x = 5
y = 10
z = 15

# Проверка цепочки:
if x < y < z:
    print("x меньше y, а y меньше z")

# Цепочка присваиваний с операциями:
result = x + y + z
print(f"Сумма: {result}")
