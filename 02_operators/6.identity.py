"""
ОПЕРАТОРЫ ТОЖДЕСТВЕННОСТИ В PYTHON
====================================
Операторы тождественности проверяют, ссылаются ли переменные
на один и тот же объект в памяти (а не на равенство значений).

Отличие от операторов сравнения (==, !=):
- == сравнивает ЗНАЧЕНИЯ объектов
- is сравнивает АДРЕСА объектов в памяти

Преимущество: можно сравнивать объекты разных типов без ошибки TypeError.
"""

# ============================================
# IS — ПРОВЕРКА ТОЖДЕСТВЕННОСТИ
# ============================================
# True, если оба операнда указывают на один и тот же объект

a = [1, 2, 3]
b = a  # 'b' ссылается на тот же объект, что и 'a'
c = [1, 2, 3]  # 'c' ссылается на другой объект с тем же значением

print(f"a is b: {a is b}")  # True (тот же объект)
print(f"a is c: {a is c}")  # False (разные объекты с одинаковым значением)

# Сравнение значений vs тождественности:
print(f"\na == b: {a == b}")  # True (значения равны)
print(f"a == c: {a == c}")  # True (значения равны)
print(f"a is b: {a is b}")  # True (тот же объект)
print(f"a is c: {a is c}")  # False (разные объекты)

# Проверка адресов объектов:
print(f"\nid(a) = {id(a)}")
print(f"id(b) = {id(b)}")
print(f"id(c) = {id(c)}")

# ============================================
# IS NOT — ПРОВЕРКА НЕТОЖДЕСТВЕННОСТИ
# ============================================
# True, если оба операнда указывают на разные объекты

print(f"\na is not b: {a is not b}")  # False (тот же объект)
print(f"a is not c: {a is not c}")  # True (разные объекты)

# ============================================
# ОСОБЕННОСТИ РАБОТЫ С НЕИЗМЕНЯЕМЫМИ ТИПАМИ
# ============================================

# Python может кэшировать небольшие целые числа и строки:
x = 5
y = 5
print(f"\n5 is 5: {x is y}")  # True (кэширование)

x = 1000
y = 1000
print(f"1000 is 1000: {x is y}")  # Может быть False! (зависит от реализации)

# Строки также могут кэшироваться:
str1 = "hello"
str2 = "hello"
print(f"'hello' is 'hello': {str1 is str2}")  # True (кэширование)

# Но для больших строк:
str1 = "hello world " * 100
str2 = "hello world " * 100
print(f"Длинные строки is: {str1 is str2}")  # False (не кэшируются)

# ============================================
# ПРАВИЛЬНОЕ ИСПОЛЬЗОВАНИЕ
# ============================================

# 1. Всегда используйте is для сравнения с None:
value = None
if value is None:
    print("\nЗначение отсутствует")

# НЕ рекомендуется:
if value == None:
    print("Так делать не стоит")

# 2. Используйте is для проверки булевых значений:
flag = True
if flag is True:
    print("Флаг истинен")

# 3. Для чисел и строк используйте == (сравнение значений):
a = 1000
b = 1000
if a == b:
    print("Числа равны по значению")

# ============================================
# ИЗМЕНЯЕМЫЕ VS НЕИЗМЕНЯЕМЫЕ ОБЪЕКТЫ
# ============================================

# Изменяемые объекты (списки, словари):
list1 = [1, 2, 3]
list2 = [1, 2, 3]
print(f"\nСписки: list1 is list2: {list1 is list2}")  # False (разные объекты)

list3 = list1
print(f"list1 is list3: {list1 is list3}")  # True (тот же объект)

# Изменение одного влияет на другой:
list3.append(4)
print(f"list1 после изменения list3: {list1}")  # [1, 2, 3, 4]

# Неизменяемые объекты (числа, строки, кортежи):
num1 = 42
num2 = 42
print(f"\nЧисла: num1 is num2: {num1 is num2}")  # True (кэширование)

tuple1 = (1, 2, 3)
tuple2 = (1, 2, 3)
print(f"Кортежи: tuple1 is tuple2: {tuple1 is tuple2}")  # Может быть True или False


# ============================================
# ПРАКТИЧЕСКИЕ ПРИМЕРЫ
# ============================================

# Проверка на None в функциях:
def find_user(user_id):
    # Имитация поиска пользователя
    users = {1: "Alice", 2: "Bob"}
    return users.get(user_id)  # Вернёт None, если пользователь не найден


user = find_user(3)
if user is None:
    print("\nПользователь не найден")


# Проверка, что возвращён тот же объект:
class Singleton:
    _instance = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super().__new__(cls)
        return cls._instance


obj1 = Singleton()
obj2 = Singleton()
print(f"\nСинглтон: obj1 is obj2: {obj1 is obj2}")  # True

# Сравнение с False и True:
result = 5 > 10
if result is False:
    print("Условие ложно")
