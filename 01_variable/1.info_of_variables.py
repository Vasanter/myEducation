"""
ПЕРЕМЕННЫЕ В PYTHON
====================
Переменная — это именованная ссылка на объект в памяти.
Каждая переменная имеет: имя, значение и тип.
"""

# ============================================
# 1. СТРУКТУРА ПЕРЕМЕННОЙ
# ============================================

# Переменная состоит из трёх частей:
# 1. Имя (идентификатор) — название для обращения к переменной
# 2. Значение — данные, хранящиеся в памяти
# 3. Тип — определяет, какие операции можно выполнять

# Пример:
my_age = 25  # имя: my_age, значение: 25, тип: int (целое число)

# Определение типа переменной:
myName = 'Vladimir'
print(type(myName))  # <class 'str'> — строковый тип

# Другие примеры типов:
age = 30
print(type(age))  # <class 'int'> — целое число

height = 1.75
print(type(height))  # <class 'float'> — число с плавающей точкой

is_student = True
print(type(is_student))  # <class 'bool'> — логический тип

# Идентификатор объекта в памяти:
print(id(myName))  # уникальный номер объекта в памяти

# ============================================
# 2. ДИНАМИЧЕСКАЯ ТИПИЗАЦИЯ
# ============================================

# Python — язык с динамической типизацией:
x = 10  # x — целое число
print(type(x))  # <class 'int'>

x = "Привет"  # теперь x — строка
print(type(x))  # <class 'str'>

x = [1, 2, 3]  # теперь x — список
print(type(x))  # <class 'list'>

# Переменная может менять не только значение, но и тип!


# ============================================
# 3. МНОЖЕСТВЕННОЕ ПРИСВАИВАНИЕ
# ============================================

# Присваивание нескольких переменных одновременно:
a, b, c = 1, 2, 3
print(a, b, c)  # 1 2 3

# Обмен значениями без временной переменной:
a, b = b, a
print(a, b)  # 2 1

# Распаковка последовательности:
numbers = [10, 20, 30]
first, second, third = numbers
print(first, second, third)  # 10 20 30

# Звёздочка для распаковки:
first, *rest = [1, 2, 3, 4, 5]
print(first)  # 1
print(rest)  # [2, 3, 4, 5]

# ============================================
# 4. СТИЛИ ИМЕНОВАНИЯ ПЕРЕМЕННЫХ
# ============================================

# Python следует PEP 8 — руководству по стилю кода:

# snake_case — переменные, функции, методы, модули:
user_name = "Иван"
total_sum = 100


def calculate_average():
    pass


# CamelCase (PascalCase) — классы:
class UserProfile:
    pass


class DatabaseConnection:
    pass


# kebab-case — названия пакетов (в файловой системе):
# my-package/
#   my_module.py

# CONSTANT_CASE — константы (не изменяются):
MAX_CONNECTIONS = 100
PI = 3.14159
DEFAULT_TIMEOUT = 30

# Булевы переменные — часто с префиксом is_, has_, can_:
is_active = True
has_permission = False
can_edit = True
is_logged_in = False

# ============================================
# 5. ПРАВИЛА ИМЕНОВАНИЯ
# ============================================

# ПРАВИЛЬНО:
