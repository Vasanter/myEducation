# 6. ОБРАБОТКА РАСПРОСТРАНЁННЫХ ОШИБОК
# ============================================

# Ошибка: попытка преобразовать нечисловую строку
# int('abc')  # ValueError: invalid literal for int() with base 10: 'abc'

# Ошибка: ввод пустой строки
# int('')  # ValueError: invalid literal for int() with base 10: ''

# Ошибка: лишние пробелы
# int(' 42 ')  # Работает! Но лучше использовать strip()
# int('42\n')  # Работает! input() удаляет \n

# Безопасное преобразование:
def safe_int_input(prompt):
    """Безопасный ввод целого числа с обработкой ошибок"""
    while True:
        try:
            return int(input(prompt).strip())
        except ValueError:
            print('Ошибка! Введите целое число.')
        except KeyboardInterrupt:
            print('\nВвод прерван пользователем')
            return None


# Использование функции:
