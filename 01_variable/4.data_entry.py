def show_menu():
    print('\n=== МЕНЮ ===')
    print('1. Показать приветствие')
    print('2. Показать текущую дату')
    print('3. Выйти')

    choice = input('Выберите пункт: ')

    if choice == '1':
        print('Привет, пользователь!')
    elif choice == '2':
        from datetime import datetime
        print(f'Сегодня: {datetime.now().strftime("%d.%m.%Y %H:%M:%S")}')
    elif choice == '3':
        print('До свидания!')
        return
    else:
        print('Неверный выбор!')

    show_menu()  # рекурсивный вызов для продолжения


