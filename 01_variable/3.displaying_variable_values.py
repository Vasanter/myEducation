# ============================================
# 1. ФУНКЦИЯ PRINT() — ОСНОВЫ
# ============================================

# Синтаксис: print(*objects, sep=' ', end='\n', file=sys.stdout, flush=False)
# Параметры:
# *objects — выводимые объекты
# sep — разделитель между объектами (по умолчанию пробел)
# end — строка в конце вывода (по умолчанию перевод строки)
# file — куда выводить (по умолчанию в консоль)
# flush — принудительная запись в поток

# Простой вывод:
print("Привет, мир!")  # Привет, мир!

# Несколько аргументов:
print("Hello", "World", "!")  # Hello World !

# Использование sep:
print(1, 2, 3, sep='-')  # 1-2-3
print("a", "b", "c", sep=" | ")  # a | b | c
print("Hello", "World", sep="")  # HelloWorld (без разделителя)

# Использование end:
print("Первая строка", end=' ')
print("Вторая строка")  # Первая строка Вторая строка
print("Без перевода", end=' => ')
print("продолжение")  # Без перевода => продолжение

# ============================================
# 2. ФОРМАТИРОВАНИЕ СТРОК
# ============================================

name = 'John'
age = 25
height = 1.75
pi = 3.14159265359

# Способ 1: Конкатенация (не рекомендуется):
print('Меня зовут ' + name + ' и мне ' + str(age) + ' лет')

# Способ 2: Оператор % (старый способ):
print('Меня зовут %s и мне %d лет' % (name, age))
print('Число Пи: %.2f' % pi)  # 3.14

# Способ 3: Метод format():
print('Меня зовут {} и мне {} лет'.format(name, age))
print('Меня зовут {0} и мне {1} лет'.format(name, age))
print('Меня зовут {n} и мне {a} лет'.format(n=name, a=age))

# Способ 4: F-строки (рекомендуемый, Python 3.6+):
print(f'Меня зовут {name} и мне {age} лет!')
print(f'Число Пи с точностью 3 знака: {pi:.3f}')
print(f'Проценты: {0.25:.0%}')  # 25%
print(f'Число с ведущими нулями: {42:05d}')  # 00042
print(f'Выравнивание: |{name:<10}|{name:>10}|{name:^10}|')

# Форматирование чисел:
big_number = 1000000
print(f'С разделителями: {big_number:,}')  # 1,000,000
print(f'В двоичной системе: {42:b}')  # 101010
print(f'В шестнадцатеричной: {255:x}')  # ff
print(f'В научной нотации: {123456789:e}')  # 1.234568e+08

# ============================================
# 3. УПРАВЛЯЮЩИЕ ПОСЛЕДОВАТЕЛЬНОСТИ
# ============================================

# Специальные символы, начинающиеся с обратной косой черты (\)

print("Основные escape-последовательности:")
print("\\n — перевод строки")
print("\\t — горизонтальная табуляция")
print("\\r — возврат каретки")
print("\\b — возврат на символ назад")
print("\\f — перевод страницы")
print("\\v — вертикальная табуляция")
print("\\a — звуковой сигнал")
print("\\\\ — обратная косая черта")
print("\\' — одинарная кавычка")
print('\\" — двойная кавычка')

# Примеры использования:
print('Еще ', 'один', 'пример', sep=' ~ ', end='  =>\t!!!')  # Еще  ~ один ~ пример  =>	!!!
print("Что", 'будем', "делать?", sep="\n")  # каждое слово на новой строке
print("Написал: '\tПривет, мир!'")  # Написал: '	Привет, мир!'
print('Другой пример ', '\nпо', 'переносу строк!', sep='\n\t')

# Практические примеры:
print("Список покупок:\n\t1. Хлеб\n\t2. Молоко\n\t3. Яйца")

# Создание таблицы:
print("Имя\t\tВозраст\tГород")
print("Анна\t25\t\tМосква")
print("Иван\t30\t\tСПб")

# Возврат каретки (перезапись строки):
import time

for i in range(10):
    print(f'\rПрогресс: {i * 10}%', end='', flush=True)
    time.sleep(0.1)
print('\rПрогресс: 100% - Готово!')

