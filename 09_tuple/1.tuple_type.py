"""
┌────────────────────┬──────────────────┬──────────────────┐
│  Характеристика    │  Кортеж (tuple)  │  Список (list)   │
├────────────────────┼──────────────────┼──────────────────┤
│  Изменяемость      │  Нет             │  Да              │
│  Синтаксис         │  (1, 2, 3)       │  [1, 2, 3]       │
│  Производительность│  Быстрее         │  Медленнее       │
│  Память            │  Меньше          │  Больше          │
│  Хешируемость      │  Да              │  Нет             │
│  Ключ словаря      │  Можно           │  Нельзя          │
│  Методы            │  count, index    │  Много методов   │
│  Когда использовать│  Неизменяемые    │  Изменяемые      │
│                    │  данные          │  данные          │
└────────────────────┴──────────────────┴──────────────────┘
"""

# Когда использовать кортеж:
# ✅ Для неизменяемых данных (дни недели, месяцы)
# ✅ Для возврата нескольких значений из функции
# ✅ Для ключей словаря
# ✅ Для защиты данных от изменений
# ✅ Когда нужна производительность

# Когда использовать список:
# ✅ Для изменяемых данных
# ✅ Когда нужно добавлять/удалять элементы
# ✅ Для коллекций с частыми изменениями


