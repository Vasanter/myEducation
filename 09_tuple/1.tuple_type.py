# ❌ Ошибка 1: Забыли запятую для кортежа с одним элементом
not_tuple = ("apple")      # это строка!
print(type(not_tuple))     # <class 'str'>

# ✅ Решение:
my_tuple = ("apple",)
print(type(my_tuple))      # <class 'tuple'>

# ❌ Ошибка 2: Попытка изменить кортеж
# user_roles = ("admin", "editor")
# user_roles[0] = "superadmin"  # TypeError!

# ✅ Решение: создать новый кортеж
user_roles = ("admin", "editor")
new_roles = ("superadmin",) + user_roles[1:]
print(new_roles)  # ('superadmin', 'editor')

# ❌ Ошибка 3: Использование кортежа с изменяемыми элементами как ключа словаря
# bad_key = (1, [2, 3])  # TypeError: unhashable type: 'list'

# ✅ Решение: использовать только неизменяемые элементы
good_key = (1, 2, 3)
locations = {good_key: "value"}
print(locations)