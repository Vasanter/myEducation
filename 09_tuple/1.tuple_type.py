"""
КОРТЕЖИ (TUPLE) В PYTHON
==========================
Кортеж — неизменяемый (immutable) упорядоченный тип данных,
предназначенный для хранения последовательности элементов.

Основные свойства:
- Неизменяемость: после создания нельзя добавить, удалить или заменить элементы
- Упорядоченность: элементы хранятся в определённом порядке (индексация с 0)
- Гибкость: могут содержать объекты любых типов, включая другие кортежи и списки
- Хешируемость: могут быть ключами словаря (если содержат только неизменяемые объекты)
"""

# ============================================
# 1. СОЗДАНИЕ КОРТЕЖЕЙ
# ============================================

# Пустой кортеж:
empty = ()
print(empty)  # ()

# Кортеж с элементами (скобки):
user_roles = ("admin", "editor", "viewer")
print(user_roles)  # ('admin', 'editor', 'viewer')

# Кортеж без скобок (упаковка):
coordinates = 10, 20
print(coordinates)  # (10, 20)

# ⚠️ ВАЖНО: кортеж с одним элементом требует запятой!
not_tuple = ("apple")          # это строка, не кортеж!
print(type(not_tuple))         # <class 'str'>

my_tuple = ("apple",)          # это кортеж (запятая обязательна!)
print(type(my_tuple))          # <class 'tuple'>

# Преобразование в кортеж:
print(tuple([1, 2, 3]))        # (1, 2, 3)
print(tuple("hello"))          # ('h', 'e', 'l', 'l', 'o')
print(tuple(range(5)))         # (0, 1, 2, 3, 4)


# ============================================
# 2. ДОСТУП К ЭЛЕМЕНТАМ
# ============================================

user_roles = ("admin", "editor", "viewer")

# По индексу:
print(user_roles[0])   # 'admin' — первый элемент
print(user_roles[1])   # 'editor'
print(user_roles[-1])  # 'viewer' — последний элемент

# Срезы (возвращают новый кортеж):
print(user_roles[0:2])   # ('admin', 'editor')
print(user_roles[::-1])  # ('viewer', 'editor', 'admin')

# Длина кортежа:
print(len(user_roles))  # 3

# Проверка наличия элемента:
print("admin" in user_roles)    # True
print("writer" in user_roles)   # False


# ============================================
# 3. НЕИЗМЕНЯЕМОСТЬ КОРТЕЖЕЙ
# ============================================

user_roles = ("admin", "editor", "viewer")

# ❌ Нельзя изменить элемент:
# user_roles[1] = "author"  # TypeError: 'tuple' object does not support item assignment

# ❌ Нельзя добавить элемент:
# user_roles.append("author")  # AttributeError: 'tuple' object has no attribute 'append'

# ❌ Нельзя удалить элемент:
# del user_roles[0]  # TypeError: 'tuple' object doesn't support item deletion

# ✅ Но можно создать новый кортеж на основе старого:
new_roles = user_roles + ("author",)
print(new_roles)  # ('admin', 'editor', 'viewer', 'author')

# ✅ Можно изменить вложенный изменяемый объект:
mixed = (1, [2, 3], 4)
mixed[1].append(99)  # изменяем список внутри кортежа
print(mixed)  # (1, [2, 3, 99], 4)


# ============================================
# 4. ПЕРЕБОР ЭЛЕМЕНТОВ
# ============================================

user_roles = ("admin", "editor", "viewer")

# Простой перебор:
for role in user_roles:
    print(role)
# admin
# editor
# viewer

# С индексами через enumerate:
for i, role in enumerate(user_roles, start=1):
    print(f"{i}. {role}")
# 1. admin
# 2. editor
# 3. viewer


# ============================================
# 5. РАСПАКОВКА КОРТЕЖЕЙ
# ============================================

# Базовая распаковка:
user_roles = ("admin", "editor", "viewer")
role_1, role_2, role_3 = user_roles
print(role_1)  # 'admin'
print(role_2)  # 'editor'
print(role_3)  # 'viewer'

# Распаковка работает и со списками:
user_roles = ["admin", "editor", "viewer"]
role_1, role_2, role_3 = user_roles
print(role_1)  # 'admin'

# Игнорирование значений через _:
role_1, role_2, _ = user_roles
print(role_1)  # 'admin'
print(role_2)  # 'editor'

# Распаковка с звёздочкой (*):
numbers = (1, 2, 3, 4, 5)
first, *middle, last = numbers
print(first)   # 1
print(middle)  # [2, 3, 4]
print(last)    # 5

# Обмен значений через кортеж:
a, b = 1, 2
a, b = b, a
print(a, b)  # 2 1


# ============================================
# 6. ОПЕРАЦИИ С КОРТЕЖАМИ
# ============================================

# Конкатенация (создаёт новый кортеж):
tuple_1 = (1, 2, 3)
tuple_2 = (4, 5, 6)
print(tuple_1 + tuple_2)  # (1, 2, 3, 4, 5, 6)

# Повторение:
print((1, 2) * 3)  # (1, 2, 1, 2, 1, 2)

# Сравнение:
print((1, 2, 3) == (1, 2, 3))  # True
print((1, 2, 3) == (1, 3, 2))  # False
print((1, 2) < (1, 2, 3))      # True

# Методы кортежей (их всего два!):
numbers = (1, 2, 3, 2, 4, 2)
print(numbers.count(2))    # 3 — количество вхождений
print(numbers.index(3))    # 2 — индекс первого вхождения


# ============================================
# 7. ПРИМЕНЕНИЕ КОРТЕЖЕЙ
# ============================================

# 1. Возврат нескольких значений из функции:
def get_user_info():
    return "Alice", 30, "New York"  # возвращает кортеж

name, age, city = get_user_info()
print(f"{name}, {age}, {city}")  # Alice, 30, New York

# 2. Координаты:
point = (10, 20)
x, y = point
print(f"x = {x}, y = {y}")

# 3. Ключи словаря (кортежи хешируемы):
locations = {
    (0, 0): "Начало координат",
    (1, 0): "Точка на оси X",
    (0, 1): "Точка на оси Y"
}
print(locations[(0, 0)])  # Начало координат

# 4. Группировка данных:
employees = [
    ("Alice", 50000),
    ("Bob", 60000),
    ("Charlie", 70000)
]
for name, salary in employees:
    print(f"{name}: {salary}")


